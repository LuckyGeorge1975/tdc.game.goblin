// Publish measured bounds only after verifying the corresponding committed images.
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const root=new URL('../',import.meta.url);
const icons=JSON.parse(readFileSync(new URL('assets/unit-art/map-icons-source.json',root)));
const pins=JSON.parse(readFileSync(new URL('assets/unit-art/objective-pins-source.json',root)));
function measured(entry,width,height){
  const bytes=readFileSync(new URL(entry.runtimePath,root));
  if(createHash('sha256').update(bytes).digest('hex')!==entry.runtimeSha256)
    throw Error(`Geometry receipt does not match ${entry.runtimePath}`);
  const bounds=entry.runtimeAlphaBounds;
  if(!Array.isArray(bounds)||bounds.length!==4||!bounds.every(Number.isFinite)||
      bounds[0]<0||bounds[1]<0||bounds[2]>width||bounds[3]>height||
      bounds[0]>=bounds[2]||bounds[1]>=bounds[3])throw Error('Invalid measured bounds');
  return {width,height,bounds};
}
const data={schemaVersion:1,sourceCommit:icons.sourceCommit,
  icons:Object.fromEntries(icons.icons.map(entry=>[entry.runtimePath,measured(entry,icons.export.size,icons.export.size)])),
  pins:Object.fromEntries(pins.pins.map(entry=>[entry.runtimePath,
    {...measured(entry,...pins.export.size),referenceCanvas:pins.export.referenceCanvas}]))};
if(data.sourceCommit!==pins.sourceCommit)throw Error('Mixed geometry provenance');
const output='// Generated by scripts/export-marker-geometry.mjs from hashed image receipts.\n'+
  '(function(root){const data='+JSON.stringify(data)+';\n'+
  'const freeze=value=>{if(value&&typeof value==="object"){Object.values(value).forEach(freeze);Object.freeze(value);}return value;};\n'+
  'root.GoblinMarkerGeometry=freeze(data);})(globalThis);\n';
writeFileSync(new URL('assets/unit-art/marker-geometry.js',root),output);
console.log(`Verified geometry for ${icons.icons.length} icons and ${pins.pins.length} pins.`);
